export const statuses: AdStatus[] = ["Pending", "Active", "Rejected", "Sold"]

function initialsOf(name: string) {
  return name
    .split(" ")
    .map((p) => p[0])
    .slice(0, 2)
    .join("")
    .toUpperCase()
}

function ad(input: Omit<Ad, "user" | "views" | "clicks" | "favorites"> & {
  userName: string
  views: number
  clicks: number
}): Ad {
  return {
    ...input,
    user: { name: input.userName, initials: initialsOf(input.userName) },
    favorites: Math.round(input.views * 0.04),
  }
}

