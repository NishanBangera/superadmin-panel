export type AdStatus = "Pending" | "Active" | "Rejected" | "Sold"

export type Ad = {
  id: string
  title: string
  category: string
  location: string
  user: { name: string; initials: string }
  status: AdStatus
  price: number
  postedDate: string
  expiryDate: string
  featured: boolean
  views: number
  clicks: number
  favorites: number
  rejectionReason?: string
  description: string
}

